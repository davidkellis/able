func bytecodeOpName(op bytecodeOp) string {
	idx := int(op)
	if idx >= 0 && idx < len(bytecodeOpNames) {
		if name := bytecodeOpNames[idx]; name != "" {
			return name
		}
	}
	return fmt.Sprintf("Op%d", idx)
}
